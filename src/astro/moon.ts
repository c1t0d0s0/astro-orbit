export interface MoonPosition {
  /** 黄経 (°) */
  lon: number;
  /** 黄緯 (°)。月の通り道は黄道から 5° ほどかたむいている */
  lat: number;
  /** 地球の中心からの距離 (km) */
  dist: number;
}

export function moonPosition(jd: number): MoonPosition {
  const t = centuries(jd);
  const t2 = t * t;
  const t3 = t2 * t;
  const t4 = t3 * t;
  const lp = 218.3164477 + 481267.88123421 * t - 0.0015786 * t2 + t3 / 538841 - t4 / 65194000;
  const d = 297.8501921 + 445267.1114034 * t - 0.0018819 * t2 + t3 / 545868 - t4 / 113065000;
  const m = 357.5291092 + 35999.0502909 * t - 0.0001536 * t2 + t3 / 24490000;
  const mp = 134.9633964 + 477198.8675055 * t + 0.0087414 * t2 + t3 / 69699 - t4 / 14712000;
  const f = 93.272095 + 483202.0175233 * t - 0.0036539 * t2 - t3 / 3526000 + t4 / 863310000;
  const a1 = 119.75 + 131.849 * t;
  const a2 = 53.09 + 479264.29 * t;
  const a3 = 313.45 + 481266.484 * t;
  const e = 1 - 0.002516 * t - 0.0000074 * t2;
  // 太陽の近点角 M をふくむ項は、地球の軌道の離心率が少しずつ変わる分 (E) をかける
  const ecc = (k: number) => (k === 0 ? 1 : Math.abs(k) === 1 ? e : e * e);

  let sl = 0;
  let sr = 0;
  for (const [cd, cm, cmp, cf, l, r] of LON_DIST) {
    const arg = cd * d + cm * m + cmp * mp + cf * f;
    sl += l * ecc(cm) * sin(arg);
    sr += r * ecc(cm) * cos(arg);
  }
  let sb = 0;
  for (const [cd, cm, cmp, cf, b] of LAT) sb += b * ecc(cm) * sin(cd * d + cm * m + cmp * mp + cf * f);
  sl += 3958 * sin(a1) + 1962 * sin(lp - f) + 318 * sin(a2);
  sb += -2235 * sin(lp) + 382 * sin(a3) + 175 * sin(a1 - f) + 175 * sin(a1 + f) + 127 * sin(lp - mp) - 115 * sin(lp + mp);

  return { lon: norm360(lp + sl / 1e6), lat: sb / 1e6, dist: 385000.56 + sr / 1000 };
}
